const (
	healthMonitoringNamePrefix = "hm-"

	// healthChecksIgnoredReason is the reason of the Warning event emitted when a Profile lists
	// HealthChecks, which only a ClusterProfile can do
	healthChecksIgnoredReason = "HealthChecksIgnored"

	// defaultHealthCheckLivenessName is the name of the liveness check referencing the
	// HealthCheck generated by addon-controller
	defaultHealthCheckLivenessName = "deployed-resources"

	// healthMonitoringFlappingEvaluations is the number of consecutive evaluations a
	// resource must be found not Healthy before it is reported
	healthMonitoringFlappingEvaluations = 3

	statefulSetKind           = "StatefulSet"
	daemonSetKind             = "DaemonSet"
	jobKind                   = "Job"
	persistentVolumeClaimKind = "PersistentVolumeClaim"

	batchGroupName = "batch"
	coreGroupName  = ""

	// monitoredAPIVersion is the version all the monitored kinds are served from
	// (apps/v1, batch/v1 and v1)
	monitoredAPIVersion = "v1"
)

var (
	// healthMonitoringLua is the Lua code evaluating the health of the resources. The
	// Lua "config" table is prepended to it, see healthMonitoringLuaConfig.
	//
	//go:embed healthmonitoring/health.lua
	healthMonitoringLua string

	// monitoredKinds are the kinds the default health checks cover
	monitoredKinds = []monitoredKind{
		{group: appsGroupName, kind: deploymentKind},
		{group: appsGroupName, kind: statefulSetKind},
		{group: appsGroupName, kind: daemonSetKind},
		{group: batchGroupName, kind: jobKind},
		{group: coreGroupName, kind: persistentVolumeClaimKind},
	}
)

// monitoredKind identifies a kind (version is always monitoredAPIVersion) covered by the default health checks
type monitoredKind struct {
	group string
	kind  string
}

// helmRelease identifies a Helm release deployed by a ClusterSummary
type helmRelease struct {
	namespace string
	name      string
}

// healthMonitoringLuaConfig contains what the Lua code needs to select, among all the
// resources found in the cluster, the ones deployed by a given profile.
type healthMonitoringLuaConfig struct {
	ownerKind    string
	ownerName    string
	helmReleases []helmRelease
}

// isHealthMonitoringEnabled returns true if health monitoring has been requested
func isHealthMonitoringEnabled(clusterSummary *configv1beta1.ClusterSummary) bool {
	hm := clusterSummary.Spec.ClusterProfileSpec.HealthMonitoring
	return hm != nil && hm.Enabled
}

// useDefaultHealthChecks returns true if the health of the resources deployed by the
// profile must be monitored. Default is true.
func useDefaultHealthChecks(hm *configv1beta1.HealthMonitoring) bool {
	return hm.DefaultChecks == nil || *hm.DefaultChecks
}

// getHealthMonitoringName returns the name of the HealthCheck and of the ClusterHealthCheck
// created for a ClusterSummary. Both are cluster scoped: the name is derived from the
// ClusterSummary UID so that it is unique, short and stable.
func getHealthMonitoringName(clusterSummary *configv1beta1.ClusterSummary) string {
	sum := sha256.Sum256([]byte(clusterSummary.UID))
	return healthMonitoringNamePrefix + hex.EncodeToString(sum[:])[:12]
}

func getHealthMonitoringLabels(clusterSummary *configv1beta1.ClusterSummary) map[string]string {
	return map[string]string{
		configv1beta1.HealthMonitoringClusterSummaryUIDLabel: string(clusterSummary.UID),
	}
}

func getHealthMonitoringAnnotations(clusterSummary *configv1beta1.ClusterSummary) map[string]string {
	return map[string]string{
		configv1beta1.HealthMonitoringClusterSummaryNamespaceAnnotation: clusterSummary.Namespace,
		configv1beta1.HealthMonitoringClusterSummaryNameAnnotation:      clusterSummary.Name,
	}
}

// getClusterSummaryClusterRef returns a reference to the cluster a ClusterSummary targets
func getClusterSummaryClusterRef(clusterSummary *configv1beta1.ClusterSummary) corev1.ObjectReference {
	clusterRef := corev1.ObjectReference{
		Namespace: clusterSummary.Spec.ClusterNamespace,
		Name:      clusterSummary.Spec.ClusterName,
	}
	if clusterSummary.Spec.ClusterType == libsveltosv1beta1.ClusterTypeSveltos {
		clusterRef.Kind = libsveltosv1beta1.SveltosClusterKind
		clusterRef.APIVersion = libsveltosv1beta1.GroupVersion.String()
	} else {
		clusterRef.Kind = clusterKind
		clusterRef.APIVersion = clusterv1.GroupVersion.String()
	}
	return clusterRef
}

// areAllFeaturesProvisioned returns true if the ClusterSummary has features and all of them are provisioned
func areAllFeaturesProvisioned(clusterSummary *configv1beta1.ClusterSummary) bool {
	if len(clusterSummary.Status.FeatureSummaries) == 0 {
		return false
	}
	for i := range clusterSummary.Status.FeatureSummaries {
		if clusterSummary.Status.FeatureSummaries[i].Status != libsveltosv1beta1.FeatureStatusProvisioned {
			return false
		}
	}
	return true
}

// healthMonitoringInputsChanged returns true if what health monitoring depends on changed between
// two versions of a ClusterSummary: all features becoming (or ceasing to be) provisioned, and the
// Helm releases managed by the ClusterSummary.
func healthMonitoringInputsChanged(oldClusterSummary, newClusterSummary *configv1beta1.ClusterSummary) bool {
	if areAllFeaturesProvisioned(oldClusterSummary) != areAllFeaturesProvisioned(newClusterSummary) {
		return true
	}

	return !reflect.DeepEqual(getManagedHelmReleases(oldClusterSummary), getManagedHelmReleases(newClusterSummary))
}

// getManagedHelmReleases returns the Helm releases currently managed by the ClusterSummary, sorted
func getManagedHelmReleases(clusterSummary *configv1beta1.ClusterSummary) []helmRelease {
	releases := make([]helmRelease, 0, len(clusterSummary.Status.HelmReleaseSummaries))
	for i := range clusterSummary.Status.HelmReleaseSummaries {
		summary := &clusterSummary.Status.HelmReleaseSummaries[i]
		if summary.Status != configv1beta1.HelmChartStatusManaging {
			continue
		}
		releases = append(releases, helmRelease{namespace: summary.ReleaseNamespace, name: summary.ReleaseName})
	}

	sort.Slice(releases, func(i, j int) bool {
		if releases[i].namespace != releases[j].namespace {
			return releases[i].namespace < releases[j].namespace
		}
		return releases[i].name < releases[j].name
	})

	return releases
}

// deploysRawResources returns true if the profile deploys anything but Helm charts.
// Resources deployed by Sveltos (everything but Helm charts) carry the ReasonLabel label.
func deploysRawResources(clusterSummary *configv1beta1.ClusterSummary) bool {
	spec := &clusterSummary.Spec.ClusterProfileSpec
	return len(spec.PolicyRefs) > 0 || len(spec.KustomizationRefs) > 0
}

// getMonitoringResourceSelectors returns the selectors for the resources to evaluate:
//   - for the resources deployed by Sveltos, every object with the label added by Sveltos;
//   - for each Helm release namespace, every object in that namespace (the Lua code
//     keeps only the ones belonging to a release of the profile).
func getMonitoringResourceSelectors(deployRaw bool, releases []helmRelease) []libsveltosv1beta1.ResourceSelector {
	selectors := make([]libsveltosv1beta1.ResourceSelector, 0)

	if deployRaw {
		for _, mk := range monitoredKinds {
			selectors = append(selectors, libsveltosv1beta1.ResourceSelector{
				Group: mk.group, Version: monitoredAPIVersion, Kind: mk.kind,
				LabelFilters: []libsveltosv1beta1.LabelFilter{
					{Key: deployer.ReasonLabel, Operation: libsveltosv1beta1.OperationHas},
				},
			})
		}
	}

	namespaces := make(map[string]bool)
	for i := range releases {
		namespaces[releases[i].namespace] = true
	}
	sortedNamespaces := make([]string, 0, len(namespaces))
	for ns := range namespaces {
		sortedNamespaces = append(sortedNamespaces, ns)
	}
	sort.Strings(sortedNamespaces)

	for _, ns := range sortedNamespaces {
		for _, mk := range monitoredKinds {
			selectors = append(selectors, libsveltosv1beta1.ResourceSelector{
				Group: mk.group, Version: monitoredAPIVersion, Kind: mk.kind, Namespace: ns,
			})
		}
	}

	return selectors
}

// quoteLuaString returns s as a Lua string literal (Lua 5.1 syntax: no \x or \u escapes)
func quoteLuaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\\':
			b.WriteString(`\\`)
		case c == '"':
			b.WriteString(`\"`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\r':
			b.WriteString(`\r`)
		case c < ' ' || c == 0x7f:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// renderHealthMonitoringLua returns the script evaluating the health of the resources deployed
// by a profile: the Lua "config" table followed by the embedded Lua library.
func renderHealthMonitoringLua(config *healthMonitoringLuaConfig) string {
	var b strings.Builder
	b.WriteString("local config = {\n")
	fmt.Fprintf(&b, "  ownerKind = %s,\n", quoteLuaString(config.ownerKind))
	fmt.Fprintf(&b, "  ownerName = %s,\n", quoteLuaString(config.ownerName))
	b.WriteString("  helmReleases = {\n")
	for _, release := range config.helmReleases {
		fmt.Fprintf(&b, "    [%s] = true,\n", quoteLuaString(release.namespace+"/"+release.name))
	}
	b.WriteString("  },\n}\n\n")
	b.WriteString(healthMonitoringLua)
	return b.String()
}

// buildMonitoringHealthCheck returns the HealthCheck evaluating the health of the resources deployed
// by the profile owning the ClusterSummary. Returns nil if there is nothing to monitor.
func buildMonitoringHealthCheck(clusterSummary *configv1beta1.ClusterSummary, profileKind, profileName string,
) *libsveltosv1beta1.HealthCheck {

	releases := getManagedHelmReleases(clusterSummary)
	selectors := getMonitoringResourceSelectors(deploysRawResources(clusterSummary), releases)
	if len(selectors) == 0 {
		return nil
	}

	script := renderHealthMonitoringLua(&healthMonitoringLuaConfig{
		ownerKind: profileKind, ownerName: profileName, helmReleases: releases,
	})

	return &libsveltosv1beta1.HealthCheck{
		ObjectMeta: metav1.ObjectMeta{
			Name:        getHealthMonitoringName(clusterSummary),
			Labels:      getHealthMonitoringLabels(clusterSummary),
			Annotations: getHealthMonitoringAnnotations(clusterSummary),
		},
		Spec: libsveltosv1beta1.HealthCheckSpec{
			ResourceSelectors:     selectors,
			EvaluateHealth:        script,
			EvaluateIndependently: true,
			Flapping: &libsveltosv1beta1.FlappingPolicy{
				ConsecutiveEvaluations: healthMonitoringFlappingEvaluations,
			},
		},
	}
}

func getHealthCheckLiveness(livenessName, healthCheckName string) libsveltosv1beta1.LivenessCheck {
	return libsveltosv1beta1.LivenessCheck{
		Name: livenessName,
		Type: libsveltosv1beta1.LivenessTypeHealthCheck,
		LivenessSourceRef: &corev1.ObjectReference{
			APIVersion: libsveltosv1beta1.GroupVersion.String(),
			Kind:       libsveltosv1beta1.HealthCheckKind,
			Name:       healthCheckName,
		},
	}
}

// buildMonitoringClusterHealthCheck returns the ClusterHealthCheck targeting the cluster of the
// ClusterSummary. Its liveness checks are the generated HealthCheck (when generatedHealthCheck is not
// empty) and the HealthChecks listed by the user.
func buildMonitoringClusterHealthCheck(clusterSummary *configv1beta1.ClusterSummary,
	generatedHealthCheck string, userHealthChecks []string) *libsveltosv1beta1.ClusterHealthCheck {

	livenessChecks := make([]libsveltosv1beta1.LivenessCheck, 0, len(userHealthChecks)+1)
	if generatedHealthCheck != "" {
		livenessChecks = append(livenessChecks,
			getHealthCheckLiveness(defaultHealthCheckLivenessName, generatedHealthCheck))
	}

	sortedUserHealthChecks := append([]string{}, userHealthChecks...)
	sort.Strings(sortedUserHealthChecks)
	for _, name := range sortedUserHealthChecks {
		livenessChecks = append(livenessChecks, getHealthCheckLiveness(name, name))
	}

	return &libsveltosv1beta1.ClusterHealthCheck{
		ObjectMeta: metav1.ObjectMeta{
			Name:        getHealthMonitoringName(clusterSummary),
			Labels:      getHealthMonitoringLabels(clusterSummary),
			Annotations: getHealthMonitoringAnnotations(clusterSummary),
		},
		Spec: libsveltosv1beta1.ClusterHealthCheckSpec{
			ClusterRefs:    []corev1.ObjectReference{getClusterSummaryClusterRef(clusterSummary)},
			LivenessChecks: livenessChecks,
			// Results are consumed from the HealthCheckReports. No notification is requested.
			Notifications: []libsveltosv1beta1.Notification{},
		},
	}
}

// reconcileHealthMonitoring makes sure the HealthCheck and ClusterHealthCheck needed to monitor the
// ClusterSummary exist (or do not exist when monitoring is not enabled).
// Instances are created only once all features are provisioned, so a deployment still
// in progress is not reported as unhealthy. Once created they are kept, so that the health of an
// update is reported.
func (r *ClusterSummaryReconciler) reconcileHealthMonitoring(ctx context.Context,
	clusterSummary *configv1beta1.ClusterSummary, logger logr.Logger) error {

	if !clusterSummary.DeletionTimestamp.IsZero() {
		return nil
	}

	// A DryRun ClusterSummary does not deploy anything: there is nothing to monitor
	if clusterSummary.Spec.ClusterProfileSpec.SyncMode == configv1beta1.SyncModeDryRun {
		return nil
	}

	if !isHealthMonitoringEnabled(clusterSummary) {
		return r.removeHealthMonitoring(ctx, clusterSummary, logger)
	}

	if !areAllFeaturesProvisioned(clusterSummary) {
		logger.V(logs.LogDebug).Info("not all features are provisioned yet. Health monitoring is deferred.")
		return nil
	}

	profileRef, err := configv1beta1.GetProfileRef(clusterSummary)
	if err != nil {
		return err
	}

	hm := clusterSummary.Spec.ClusterProfileSpec.HealthMonitoring
	healthChecks := r.getAllowedHealthChecks(clusterSummary, profileRef.Kind, hm)

	generatedHealthCheck := ""
	if useDefaultHealthChecks(hm) {
		healthCheck := buildMonitoringHealthCheck(clusterSummary, profileRef.Kind, profileRef.Name)
		if healthCheck != nil {
			if err := createOrUpdateMonitoringHealthCheck(ctx, r.Client, healthCheck); err != nil {
				return err
			}
			generatedHealthCheck = healthCheck.Name
		}
	}

	if generatedHealthCheck == "" && len(healthChecks) == 0 {
		// Nothing to monitor (yet): the profile does not deploy any of the monitored kinds
		return r.removeHealthMonitoring(ctx, clusterSummary, logger)
	}

	if generatedHealthCheck == "" {
		// The generated HealthCheck is not needed anymore
		if err := deleteMonitoringHealthCheck(ctx, r.Client, clusterSummary); err != nil {
			return err
		}
	}

	clusterHealthCheck := buildMonitoringClusterHealthCheck(clusterSummary, generatedHealthCheck, healthChecks)
	return createOrUpdateMonitoringClusterHealthCheck(ctx, r.Client, clusterHealthCheck)
}

// getAllowedHealthChecks returns the HealthChecks listed in healthMonitoring that can be monitored.
// Only a ClusterProfile can list HealthChecks: a HealthCheck is cluster scoped and referenced by name,
// and the report it produces is shared by all the profiles referencing it on a cluster, so a (namespaced)
// Profile could otherwise learn about resources outside its namespace. For a Profile the list is
// ignored, and a Warning event says so.
func (r *ClusterSummaryReconciler) getAllowedHealthChecks(clusterSummary *configv1beta1.ClusterSummary,
	profileKind string, hm *configv1beta1.HealthMonitoring) []string {

	if profileKind != configv1beta1.ProfileKind || len(hm.HealthChecks) == 0 {
		return hm.HealthChecks
	}

	recordEventf(r.eventRecorder, clusterSummary, nil, corev1.EventTypeWarning, healthChecksIgnoredReason,
		eventreasons.ActionReconciling,
		"healthMonitoring.healthChecks is ignored: only a ClusterProfile can reference HealthChecks, "+
			"a Profile gets the default health checks only")

	return nil
}

// removeHealthMonitoring removes the HealthCheck and ClusterHealthCheck created for the ClusterSummary
func (r *ClusterSummaryReconciler) removeHealthMonitoring(ctx context.Context,
	clusterSummary *configv1beta1.ClusterSummary, logger logr.Logger) error {

	logger.V(logs.LogDebug).Info("removing health monitoring resources, if any")

	// The ClusterHealthCheck goes first: removing it makes healthcheck-manager remove the
	// HealthCheck from the managed cluster.
	if err := deleteIfOwned(ctx, r.Client, &libsveltosv1beta1.ClusterHealthCheck{}, clusterSummary); err != nil {
		return err
	}

	return deleteMonitoringHealthCheck(ctx, r.Client, clusterSummary)
}

func deleteMonitoringHealthCheck(ctx context.Context, c client.Client,
	clusterSummary *configv1beta1.ClusterSummary) error {

	return deleteIfOwned(ctx, c, &libsveltosv1beta1.HealthCheck{}, clusterSummary)
}

// deleteIfOwned deletes the instance created for the ClusterSummary, if any. It does nothing
// if the instance does not exist, or if the CRD is not installed.
func deleteIfOwned(ctx context.Context, c client.Client, obj client.Object,
	clusterSummary *configv1beta1.ClusterSummary) error {

	obj.SetName(getHealthMonitoringName(clusterSummary))
	err := c.Get(ctx, client.ObjectKeyFromObject(obj), obj)
	if err != nil {
		if apierrors.IsNotFound(err) || meta.IsNoMatchError(err) {
			return nil
		}
		return err
	}

	// Never delete an instance this ClusterSummary did not create
	if obj.GetLabels()[configv1beta1.HealthMonitoringClusterSummaryUIDLabel] != string(clusterSummary.UID) {
		return nil
	}

	err = c.Delete(ctx, obj)
	if err != nil && !apierrors.IsNotFound(err) {
		return err
	}
	return nil
}

func createOrUpdateMonitoringHealthCheck(ctx context.Context, c client.Client,
	desired *libsveltosv1beta1.HealthCheck) error {

	healthCheck := &libsveltosv1beta1.HealthCheck{ObjectMeta: metav1.ObjectMeta{Name: desired.Name}}
	_, err := controllerutil.CreateOrUpdate(ctx, c, healthCheck, func() error {
		healthCheck.Labels = mergeStringMaps(healthCheck.Labels, desired.Labels)
		healthCheck.Annotations = mergeStringMaps(healthCheck.Annotations, desired.Annotations)
		healthCheck.Spec = desired.Spec
		return nil
	})
	return err
}

func createOrUpdateMonitoringClusterHealthCheck(ctx context.Context, c client.Client,
	desired *libsveltosv1beta1.ClusterHealthCheck) error {

	clusterHealthCheck := &libsveltosv1beta1.ClusterHealthCheck{ObjectMeta: metav1.ObjectMeta{Name: desired.Name}}
	_, err := controllerutil.CreateOrUpdate(ctx, c, clusterHealthCheck, func() error {
		clusterHealthCheck.Labels = mergeStringMaps(clusterHealthCheck.Labels, desired.Labels)
		clusterHealthCheck.Annotations = mergeStringMaps(clusterHealthCheck.Annotations, desired.Annotations)
		clusterHealthCheck.Spec = desired.Spec
		return nil
	})
	return err
}

// mergeStringMaps returns current with all the entries of desired set
func mergeStringMaps(current, desired map[string]string) map[string]string {
	if current == nil {
		current = make(map[string]string, len(desired))
	}
	for k, v := range desired {
		current[k] = v
	}
	return current
}
